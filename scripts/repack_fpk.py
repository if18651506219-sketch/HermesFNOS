#!/usr/bin/env python3
"""Re-seal an official HermesFNOS .fpk with a patched port layer.

This does NOT build from source. The official release fpk is a plain gzip tar
(no signature; the checksum is a field in the release manifest, see below):

    fpk      = app.tgz + cmd/ + config/ + ICON*.PNG + manifest
    app.tgz  = python314/ + venv/ + src/ + ui/ + seeds/ + config/ + sock_proxy.py

Every tar member is copied verbatim (name, mode, uid/gid, uname/gname, mtime,
type, pax headers). Only four port-layer members are replaced:

    cmd/main                     <- <src>/cmd/main
    manifest                     <- base fpk's manifest, version + checksum rewritten
    app.tgz!sock_proxy.py        <- <src>/sock_proxy.py
    app.tgz!src/install-stamp.json  displayVersion fnOS revision bumped

manifest.checksum MUST equal MD5(app.tgz). The release manifest (generated by
fnpack) carries that field while the checked-in repo manifest does not; using
the repo manifest directly produced an uninstallable package. This tool always
derives from the release manifest and re-computes checksum for the new app.tgz.

The bundled kernel, Linux Python 3.14 and venv stay byte-identical to the
official release, so no build NAS, fnpack or kernel source is required.

usage:
  repack_fpk.py --base HermesFNOS.fpk --src <repo> --out HermesFNOS-0.22.7.3.fpk \
                --version 0.22.7.3

The version must be higher than the installed fpk version (fnOS app center
only offers an in-place upgrade for a strictly newer version), while its first
three segments must still equal the stamped upstream kernel version.
"""
import argparse
import copy
import hashlib
import io
import json
import os
import re
import shutil
import sys
import tarfile
import tempfile
from pathlib import Path

APP = 'app.tgz'
STAMP = 'src/install-stamp.json'
PROXY = 'sock_proxy.py'
VERSION_LINE = re.compile(rb'(?m)^version\s*=\s*"?([^"\s]+)"?')


def die(msg):
    raise SystemExit('ERROR: ' + msg)


def manifest_version(raw):
    m = VERSION_LINE.search(raw)
    return m.group(1).decode() if m else ''


def rewrite_stamp(raw, version):
    """Minimal edit: change only the fnOS revision inside displayVersion."""
    m = re.search(rb'("displayVersion"\s*:\s*"[^"]*fnOS\s+)([0-9][0-9.]*)', raw)
    if not m:
        die('install-stamp.json has no fnOS displayVersion to rewrite')
    return raw[:m.start(2)] + version.encode() + raw[m.end(2):]


def rewrite_manifest(raw, version, app_md5):
    """Derive the sealed manifest from the RELEASE manifest, not the repo one.

    fnpack writes build-time fields that the checked-in manifest lacks — most
    importantly `checksum = MD5(app.tgz)`. fnOS verifies it at install time;
    a missing or stale value rejects the package. Keep every other byte of the
    release manifest verbatim, only rewrite version + checksum.
    """
    out = re.sub(rb'(?m)^version\s*=.*$', b'version = ' + version.encode(), raw, count=1)
    line = b'checksum = ' + app_md5.encode()
    if re.search(rb'(?m)^checksum\s*=', out):
        out = re.sub(rb'(?m)^checksum\s*=.*$', line, out, count=1)
    else:
        out = out.rstrip(b'\n') + b'\n' + line + b'\n'
    return out


def reseal(tin, out_path, replacements):
    """Copy all members; replacements maps member name -> bytes or open fileobj."""
    seen = set()
    count = 0
    with tarfile.open(out_path, 'w:gz', compresslevel=6) as tout:
        for m in tin:
            count += 1
            if m.name in replacements:
                obj = replacements[m.name]
                if isinstance(obj, (bytes, bytearray)):
                    size, stream = len(obj), io.BytesIO(obj)
                else:
                    size, stream = os.fstat(obj.fileno()).st_size, obj
                nm = copy.copy(m)
                nm.size = size
                tout.addfile(nm, stream)
                seen.add(m.name)
            else:
                stream = tin.extractfile(m) if m.isfile() else None
                tout.addfile(m, stream)
    missing = set(replacements) - seen
    if missing:
        die('replacement members not found: ' + ', '.join(sorted(missing)))
    return count


def fingerprint(path):
    h, m = hashlib.sha256(), hashlib.md5()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
            m.update(chunk)
    return h.hexdigest(), m.hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--base', required=True, help='official release .fpk')
    ap.add_argument('--src', required=True, help='port-layer repo directory')
    ap.add_argument('--out', required=True, help='output .fpk')
    ap.add_argument('--version', required=True, help='new fnOS version, e.g. 0.22.7.3')
    a = ap.parse_args()

    base, src, out = Path(a.base), Path(a.src), Path(a.out)
    ver = a.version
    if not re.fullmatch(r'\d+\.\d+\.\d+\.\d+', ver):
        die('version must look like 0.22.7.3')
    kernel = '.'.join(ver.split('.')[:3])
    for rel in ('manifest', 'cmd/main', PROXY, 'stamp_version.py'):
        if not (src / rel).is_file():
            die('port layer missing ' + rel)
    if out.resolve() == base.resolve():
        die('--out must not overwrite --base')

    mf = (src / 'manifest').read_bytes()
    if manifest_version(mf) != ver:
        die("src/manifest version is %s, expected %s (pass matching --version)"
            % (manifest_version(mf), ver))

    # stamp_version.py holds the upstream commit triple; refuse a mismatched seal.
    writer = (src / 'stamp_version.py').read_text(errors='ignore')
    cm = re.search(r'^COMMIT\s*=\s*"([0-9a-f]{7,40})"', writer, re.M)
    km = re.search(r'^KERNEL\s*=\s*"([0-9.]+)"', writer, re.M)
    if not cm or not km or km.group(1) != kernel:
        die('stamp_version.py KERNEL/COMMIT missing or kernel mismatch')

    tmp = tempfile.mkdtemp(prefix='hermes-repack-')
    base_app, new_app = os.path.join(tmp, 'base-app.tgz'), os.path.join(tmp, 'app.tgz')
    try:
        with tarfile.open(base, 'r:gz') as tf:
            try:
                bm = tf.getmember('manifest')
                am = tf.getmember(APP)
            except KeyError as e:
                die('base fpk missing member %s' % e)
            base_manifest = tf.extractfile(bm).read()
            bver = manifest_version(base_manifest)
            if '.'.join(bver.split('.')[:3]) != kernel:
                die('base kernel %s != requested kernel %s' % (bver, kernel))
            with tf.extractfile(am) as f, open(base_app, 'wb') as w:
                shutil.copyfileobj(f, w, 1 << 20)

        with tarfile.open(base_app, 'r:gz') as ta:
            stamp_raw = ta.extractfile(ta.getmember(STAMP)).read()
            stamp = json.loads(stamp_raw)
            if stamp.get('baseVersion') != kernel:
                die('base stamp baseVersion %r != kernel %s'
                    % (stamp.get('baseVersion'), kernel))
            if stamp.get('commit') != cm.group(1):
                die('base stamp commit %s != stamp_version.py COMMIT %s'
                    % (str(stamp.get('commit'))[:10], cm.group(1)[:10]))
            inner = {
                PROXY: (src / PROXY).read_bytes(),
                STAMP: rewrite_stamp(stamp_raw, ver),
            }
            n_inner = reseal(ta, new_app, inner)

        app_md5 = fingerprint(new_app)[1]
        sealed_manifest = rewrite_manifest(base_manifest, ver, app_md5)

        with open(new_app, 'rb') as nf, tarfile.open(base, 'r:gz') as tf:
            outer = {
                APP: nf,
                'cmd/main': (src / 'cmd/main').read_bytes(),
                'manifest': sealed_manifest,
            }
            n_outer = reseal(tf, str(out), outer)

        # Structural check: identical member list and metadata (mtime excluded;
        # PAX round-trips can change its representation but not semantics).
        def members(p):
            with tarfile.open(p, 'r:gz') as t:
                return [(m.name, m.type, m.mode, m.uid, m.gid,
                         m.uname, m.gname) for m in t]
        if members(base) != members(out):
            die('outer member list/metadata changed')
        with tarfile.open(base_app, 'r:gz') as x, tarfile.open(new_app, 'r:gz') as y:
            if members(base_app) != members(new_app):
                die('inner member list/metadata changed')

        # Content check on the sealed package itself.
        with tarfile.open(out, 'r:gz') as t:
            sealed_app = t.extractfile(APP).read()
            assert t.extractfile('cmd/main').read() == outer['cmd/main']
            sealed_mf = t.extractfile('manifest').read()
            assert sealed_mf == sealed_manifest
            mc = re.search(rb'(?m)^checksum\s*=\s*([0-9a-f]{32})\s*$', sealed_mf)
            assert mc and mc.group(1).decode() == hashlib.md5(sealed_app).hexdigest(), \
                'manifest.checksum != MD5(app.tgz)'
        with tarfile.open(fileobj=io.BytesIO(sealed_app), mode='r:gz') as t:
            assert t.extractfile(PROXY).read() == inner[PROXY]
            assert json.loads(t.extractfile(STAMP).read())['displayVersion'].endswith('fnOS %s)' % ver)

        sha, md5 = fingerprint(out)
        print('OK  %s' % out)
        print('    version      %s (kernel %s, commit %s)' % (ver, kernel, cm.group(1)[:10]))
        print('    members      outer=%d inner=%d (metadata preserved, no links added)'
              % (n_outer, n_inner))
        print('    size         %d bytes' % out.stat().st_size)
        print('    app.tgz md5  %s (manifest.checksum)' % app_md5)
        print('    sha256       %s' % sha)
        print('    md5          %s' % md5)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == '__main__':
    main()
